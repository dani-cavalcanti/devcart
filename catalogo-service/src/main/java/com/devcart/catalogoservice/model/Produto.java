package com.devcart.catalogoservice.model;

import java.math.BigDecimal;

import org.springframework.data.annotation.Id;
import org.springframework.data.mongodb.core.index.Indexed;
import org.springframework.data.mongodb.core.mapping.Document;

/**
 * Entidade de persistencia do catalogo. Uso restrito as camadas
 * repository e service - NUNCA deve ser exposta pela controller.
 */
@Document(collection = "produtos")
public class Produto {

    @Id
    private String id;

    @Indexed(unique = true)
    private String nome;

    private String descricao;

    private BigDecimal preco;

    private Integer estoque;

    public Produto() {
    }

    public Produto(String id, String nome, String descricao, BigDecimal preco, Integer estoque) {
        this.id = id;
        this.nome = nome;
        this.descricao = descricao;
        this.preco = preco;
        this.estoque = estoque;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public String getDescricao() {
        return descricao;
    }

    public void setDescricao(String descricao) {
        this.descricao = descricao;
    }

    public BigDecimal getPreco() {
        return preco;
    }

    public void setPreco(BigDecimal preco) {
        this.preco = preco;
    }

    public Integer getEstoque() {
        return estoque;
    }

    public void setEstoque(Integer estoque) {
        this.estoque = estoque;
    }
}
